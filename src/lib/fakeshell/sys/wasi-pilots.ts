export const WASI_PILOTS: Record<WasiPilotId, WasiPilot> = {
	hello: {
		id: 'hello',
		defaultPath: '/usr/lib/fakeshell/wasi-hello.wasm',
		summary: 'print "hi" and exit 0 (fd_write demo)',
		example: 'wasi-hello   (or: sys runwasm …/wasi-hello.wasm)',
		bytes: HELLO_BYTES,
	},
	echo: {
		id: 'echo',
		defaultPath: '/usr/lib/fakeshell/wasi-echo.wasm',
		summary: 'print argv[1..] like echo (args_get + fd_write)',
		example: 'wasi-echo hello world',
		bytes: ECHO_BYTES,
	},
	cat: {
		id: 'cat',
		defaultPath: '/usr/lib/fakeshell/wasi-cat.wasm',
		summary: 'print file contents (path_open + fd_read + fd_write)',
		example: 'wasi-cat /tmp/a.txt',
		bytes: CAT_BYTES,
	},
}

export function listWasiPilots(): WasiPilot[] {
	return Object.values(WASI_PILOTS)
}

export function getWasiPilot(id: string): WasiPilot | undefined {
	if (id in WASI_PILOTS) return WASI_PILOTS[id as WasiPilotId]
	// aliases
	if (id === 'wasi-hello' || id === 'hi') return WASI_PILOTS.hello
	if (id === 'wasi-echo') return WASI_PILOTS.echo
	if (id === 'wasi-cat') return WASI_PILOTS.cat
	return undefined
}

export function buildMinimalWasiHello(): Uint8Array {
	return HELLO_BYTES.slice()
}
